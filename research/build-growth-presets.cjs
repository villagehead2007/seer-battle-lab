'use strict';
// Pass the pinned api-data checkout's data/v1/sharded_data directory.
// Input is read locally. The generated browser/Node catalog has no network dependency.
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const revision='b5e91ed236b7eda33f44dd5123ef172062535ed5';
const source={repository:'https://github.com/SeerAPI/api-data',revision,date:'2026-11-20',tables:{}};
const hashByTable={mintmark:'72cdefbf',title:'36f8a2d3',equip:'11b36c30'};
function table(name){
  const directory=path.join(process.argv[2],name);
  const index=JSON.parse(fs.readFileSync(path.join(directory,'id-index.json')));
  assert.equal(index.resource_hash,hashByTable[name]);
  const result=[];
  for(const shard of Object.values(index.shards)){
    const data=JSON.parse(fs.readFileSync(path.join(directory,shard.path)));
    const records=Object.values(data).filter(row=>row&&typeof row==='object');
    assert.equal(records.length,shard.count);
    result.push(...records);
  }
  assert.deepEqual(result.map(row=>row.id).sort((a,b)=>a-b),Object.keys(index.by_id).map(Number).sort((a,b)=>a-b));
  source.tables[name]={count:result.length,hash:index.resource_hash};
  return result;
}
const fields={maxHp:'hp',atk:'atk',def:'def',spa:'sp_atk',spd:'sp_def',spe:'spd'};
function stats(value,extra){
  return Object.fromEntries(Object.entries(fields).map(([key,raw])=>{
    const n=value[raw]+(extra?.[raw]??0);
    assert.ok(Number.isInteger(n)&&n>=0);
    return [key,n];
  }));
}
// argv[3] is unity/mintmark.json at the pinned client revision. argv[4] holds
// MediaWiki query.pages responses for 刻印:<id>, including revisions, ids and content.
const clientRevision='f75e430cef29020849bf81b4fcc5ea3231552e37';
source.angleSource={url:'https://github.com/SeerAPI/config-sources/blob/'+clientRevision+'/unity/mintmark.json',field:'quality',wikiMatches:0,wikiMissing:0};
const client=new Map(JSON.parse(fs.readFileSync(process.argv[3])).mint_marks.mint_mark.map(x=>[x.id,x]));
const wiki=new Map();
for(const file of fs.readdirSync(process.argv[4]).filter(file=>file.endsWith('.json'))){
  const pages=JSON.parse(fs.readFileSync(path.join(process.argv[4],file))).query.pages;
  for(const page of Object.values(pages))wiki.set(Number(page.title.split(':')[1]),page.revisions?.[0]??null);
}
const marks=table('mintmark').filter(m=>m.type.id===3&&m.pet===null).map(m=>{
  assert.equal(m.max_attr_value.percent,false);
  assert.ok(!m.extra_attr_value?.percent);
  const raw=client.get(m.id),rev=wiki.get(m.id);
  assert.ok(raw&&raw.type===3&&!raw.monster_id.length);
  assert.ok(m.effect===null&&m.skill===null&&!raw.arg.length&&!raw.move_id.length);
  assert.ok(raw.level===100&&raw.grade===5);
  assert.ok(wiki.has(m.id)&&[2,3,4,5].includes(raw.quality));
  const wikiAngle=rev?.slots.main['*'].match(/\|角数=(\d+)/);
  if(wikiAngle){assert.equal(Number(wikiAngle[1]),raw.quality);source.angleSource.wikiMatches++;}
  else source.angleSource.wikiMissing++;
  return {id:m.id,name:m.name,angles:raw.quality,wikiRevision:rev?.revid??null,stats:stats(m.max_attr_value,m.extra_attr_value),hash:m.hash};
});
const panelOnly=/^(?:背包内(?:所有|全体)?精灵)?(?:全属性|物攻|攻击|防御|特攻|特防|速度|体力)\+\d+%?点?(?:[，,、\s]+(?:全属性|物攻|攻击|防御|特攻|特防|速度|体力)\+\d+%?点?)*$/;
const titles=table('title').filter(t=>t.is_ability_bonus&&t.attr_bonus?.total>0&&panelOnly.test(t.ability_desc)).map(t=>({
  id:t.id,name:t.name,originalName:t.original_name,stats:stats(t.attr_bonus),percent:t.attr_bonus.percent,
  effect:t.ability_desc,hash:t.hash
}));
const eyes=table('equip').filter(e=>e.part_type.id===1&&[0,1].includes(e.occasion?.id)&&e.bonus?.attribute?.total>0
  &&!e.bonus.newse_id&&!e.bonus.eid_effect&&!Object.values(e.bonus.other_attribute??{}).some(Boolean)&&panelOnly.test(e.bonus.desc)).map(e=>({
  id:e.id,name:e.name,stats:stats(e.bonus.attribute),percent:e.bonus.attribute.percent,
  effect:e.bonus.desc,occasion:e.occasion.id,hash:e.hash
}));
source.filters={marks:'mintmark_type=3, pet=null；满级六维=max_attr_value+extra_attr_value',
    titles:'纯面板能力增益，无场景限定；排除混合能力描述',
    eyes:'eye 部位、occasion 0/1，仅面板数值，无附加效果或其它属性'};
const data={source,marks,titles,eyes};
fs.writeFileSync(path.join(__dirname,'../dist/growth-catalog.js'),"// Generated by research/build-growth-presets.cjs from pinned SeerAPI data.\n(function(root,data){if(typeof module==='object'&&module.exports)module.exports=data;else root.BattleGrowthCatalog=data;})(globalThis,"+JSON.stringify(data)+");\n");
console.log({marks:marks.length,titles:titles.length,eyes:eyes.length});
